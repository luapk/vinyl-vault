"""Compose the traced script lockup (logo v2) from its three colour layers.

The source is a three-tone treatment: an acid fill, a cream inner stroke, and
a black outer keyline. The keyline is NOT traced. It sits outside the
lettering in the original, so it is regenerated by stroking the union path and
painting it behind everything: that gives a clean, adjustable keyline instead
of a traced approximation of a drop shadow, and it is what lets the whole
lockup be re-weighted or flattened to one colour later.
"""
import re, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
ACID, CREAM, INK, PAPER = '#CAFE04', '#F2F6D8', '#0D0C0A', '#F7F8F2'


def layer(name):
    """-> (viewBox w, h, transform, [path d, ...]) from a potrace SVG."""
    s = open(os.path.join(HERE, 'traces', f'{name}.svg')).read()
    vb = re.search(r'viewBox="([\d.\s]+)"', s).group(1).split()
    w, h = float(vb[2]), float(vb[3])
    tr = re.search(r'<g transform="([^"]+)"', s).group(1)
    ds = [' '.join(d.split()) for d in re.findall(r'<path d="(.*?)"', s, re.S)]
    return w, h, tr, ds


W, H, TR, UNION = layer('union')
_, _, _, ACID_D = layer('acid')

PAD = 26.0          # breathing room so the keyline is not clipped
KEY = 13.0          # keyline weight, in trace units


def svg(fill_acid, fill_cream, fill_key, bg=None):
    paths_union = ''.join(f'<path d="{d}"/>' for d in UNION)
    paths_acid = ''.join(f'<path d="{d}"/>' for d in ACID_D)
    body = []
    if bg:
        body.append(f'<rect x="0" y="0" width="{W + PAD * 2:.0f}" height="{H + PAD * 2:.0f}" fill="{bg}"/>')
    body.append(f'<g transform="translate({PAD},{PAD})">')
    if fill_key:
        body.append(
            f'<g fill="{fill_key}" stroke="{fill_key}" stroke-width="{KEY}" '
            f'stroke-linejoin="round" stroke-linecap="round" transform="{TR}">{paths_union}</g>')
    if fill_cream:
        body.append(f'<g fill="{fill_cream}" transform="{TR}">{paths_union}</g>')
    if fill_acid:
        body.append(f'<g fill="{fill_acid}" transform="{TR}">{paths_acid}</g>')
    body.append('</g>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" '
            f'viewBox="0 0 {W + PAD * 2:.0f} {H + PAD * 2:.0f}" '
            f'role="img" aria-label="Found Sound">\n  ' + '\n  '.join(body) + '\n</svg>\n')


OUT = {
    # The full three-tone treatment, as drawn.
    'script-full':        svg(ACID, CREAM, INK),
    # One colour. This fills the ACID path, not the union, so the cream ribbon
    # survives as NEGATIVE SPACE. That matters more here than on a normal
    # wordmark: this script overlaps its own strokes constantly, and the pale
    # ribbon is the only thing separating them. Filling the union instead
    # merges the overlaps and the lettering collapses into a blob.
    'script-acid':        svg(ACID, None, None),
    'script-black':       svg(INK, None, None),
    'script-white':       svg(PAPER, None, None),
    # Two-tone: lettering with its keyline, no inner fill distinction.
    'script-acid-keyed':  svg(None, ACID, INK),
    'script-white-keyed': svg(None, PAPER, INK),
}

OUT_DIR = os.path.join(HERE, 'out')

if __name__ == '__main__':
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, s in OUT.items():
        open(os.path.join(OUT_DIR, f'{name}.svg'), 'w').write(s)
        print(f'{name}.svg  {len(s):>7d} bytes')
    print(f'\nviewBox {W + PAD * 2:.0f} x {H + PAD * 2:.0f}  ratio {(W + PAD * 2) / (H + PAD * 2):.2f}')
